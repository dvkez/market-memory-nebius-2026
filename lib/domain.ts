export function canonicalUrl(input: string): string | null {
  try {
    const u = new URL(input);
    if (u.protocol !== "https:" && u.protocol !== "http:") return null;
    u.hash = "";
    for (const key of [...u.searchParams.keys()]) if (/^(utm_|fbclid|gclid)/i.test(key)) u.searchParams.delete(key);
    u.searchParams.sort();
    return u.toString().replace(/\/$/, "");
  } catch { return null; }
}
export function deduplicate(sources: Source[]): Source[] {
  const found = new Map<string, Source>();
  for (const source of sources) {
    const url = canonicalUrl(source.url);
    if (!url) continue;
    const previous = found.get(url);
    if (!previous || (!previous.publishedAt && source.publishedAt)) found.set(url, { ...source, url });
  }
  return [...found.values()];
}
// Pearson is computed on paired observations, never generated by an LLM.
export function pearson(pairs: [number, number][], minimum = 30): { r: number | null; n: number; reason: string | null } {
  const valid = pairs.filter(p => p.every(Number.isFinite));
  const n = valid.length;
  if (n < minimum) return { r: null, n, reason: "Insufficient data: at least 30 paired sessions required." };
  const mx = valid.reduce((a, p) => a + p[0], 0) / n;
  const my = valid.reduce((a, p) => a + p[1], 0) / n;
  let xx = 0, yy = 0, xy = 0;
  for (const [x, y] of valid) { xx += (x - mx) ** 2; yy += (y - my) ** 2; xy += (x - mx) * (y - my); }
  if (xx < 1e-12 || yy < 1e-12) return { r: null, n, reason: "Insufficient variation in one or both series." };
  return { r: Math.max(-1, Math.min(1, xy / Math.sqrt(xx * yy))), n, reason: null };
}
const nyParts = new Intl.DateTimeFormat("en-CA", { timeZone: "America/New_York", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", hourCycle: "h23" });
export function sessionCloseMinutes(date: string): number {
  const d=new Date(`${date}T12:00:00Z`),year=d.getUTCFullYear(),month=d.getUTCMonth()+1,day=d.getUTCDate(),weekday=d.getUTCDay();
  const novemberFirst=new Date(Date.UTC(year,10,1)).getUTCDay();
  const thanksgivingFriday=1+(4-novemberFirst+7)%7+22;
  if ((month===11&&day===thanksgivingFriday)||(weekday>=1&&weekday<=4&&((month===7&&day===3)||(month===12&&day===24)))) return 780;
  return 960;
}
export function publicationSession(published: string | null, dates: string[]): string | null {
  if (!published) return null;
  const date = new Date(published);
  if (!Number.isFinite(date.getTime())) return null;
  // A date without time is conservatively assigned to the next trading session.
  if (/^\d{4}-\d{2}-\d{2}$/.test(published)) return published < (dates[0]??published) ? null : dates.find(d => d > published) ?? null;
  const parts = Object.fromEntries(nyParts.formatToParts(date).map(p => [p.type, p.value]));
  const local = `${parts.year}-${parts.month}-${parts.day}`;
  if(local<(dates[0]??local))return null;
  const afterClose = Number(parts.hour) * 60 + Number(parts.minute) >= sessionCloseMinutes(local);
  return dates.find(d => afterClose ? d > local : d >= local) ?? null;
}
export function calculateMetrics(prices: Price[], sources: Source[], splitDates: string[] = []): Metrics {
  const sorted = [...prices].filter(p => Number.isFinite(p.close) && p.close > 0).sort((a,b) => a.date.localeCompare(b.date));
  const dates = sorted.map(p => p.date);
  const buckets = new Map<string, Source[]>();
  const unique = deduplicate(sources);
  let undated = 0;
  for (const s of unique) {
    const session = publicationSession(s.publishedAt, dates);
    if (!s.publishedAt || !Number.isFinite(new Date(s.publishedAt).getTime())) undated++;
    if (session && s.sentiment !== null) buckets.set(session, [...(buckets.get(session) ?? []), s]);
  }
  const sessions = sorted.map((p,i): SessionPoint => {
    const docs = buckets.get(p.date) ?? [];
    const raw = i ? (p.close / sorted[i-1].close - 1) * 100 : null;
    // Raw daily data: exclude known splits and large discontinuities pending adjustment review.
    const excludedReturn = splitDates.includes(p.date) || (raw !== null && Math.abs(raw) > 35);
    return { date: p.date, close: p.close, volume: p.volume, returnPct: excludedReturn ? null : raw, sentiment: docs.length ? docs.reduce((a,s) => a + s.sentiment!, 0) / docs.length : null, observed: docs.length, excludedReturn };
  });
  const correlations = ([0,1] as const).map(lag => {
    const pairs: [number,number][] = [];
    sessions.forEach((p,i) => {
      const next = sessions[i + lag];
      if (p.sentiment !== null && next?.returnPct != null) pairs.push([p.sentiment, next.returnPct]);
    });
    return { lag, ...pearson(pairs) };
  });
  return { sessions, correlations, undated, window: { from: dates[0] ?? null, to: dates.at(-1) ?? null }, retrospective: unique.some(s => s.retrospective) };
}
